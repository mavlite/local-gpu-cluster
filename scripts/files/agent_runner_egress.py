#!/usr/bin/env python3
"""Per-repo sandbox egress for the agent runner (VM 178), one table -> three enforcement points.

The table (/etc/agent-runner-agent/egress.conf, repo copy scripts/files/agent-runner-egress.conf):

    # repo      user        allowed tcp endpoints (IPv4:port, IP literals only -- the sandbox has no DNS)
    SDG-RUST    agent-rust  10.60.40.10:80 10.60.20.12:2022

Each repo runs its agent as its OWN unprivileged user, so the kernel can tell tasks apart by uid:

  user REPO       -> the sandbox user agent-run passes to systemd-run --uid
  ip-allow REPO   -> systemd IPAddressAllow= list: 127.0.0.1, ::1, the router, the repo's IPs. Never "localhost":
                     it includes systemd-resolved's stub 127.0.0.53, which gave the sandbox DNS (probe 2026-10-30).
  render-nft      -> nftables table `inet agent_egress`: per uid + IP + PORT (systemd's IP filter has no ports),
                     loopback 127.0.0.1/::1 only, the router on 8000 for every agent user, then reject.
  users           -> every agent user (setup-sandbox creates them)

The router (192.168.6.153:8000) is implicit for every repo: it is the model.
"""
import argparse
import ipaddress
import re
import sys

ROUTER = ("192.168.6.153", 8000)
DEFAULT_CONF = "/etc/agent-runner-agent/egress.conf"
_REPO = re.compile(r"^[A-Za-z0-9._-]+$")
_USER = re.compile(r"^agent-[a-z0-9]+$")


def parse(text):
    table, users = {}, set()
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) < 2:
            raise ValueError(f"line {n}: need 'REPO USER [IP:PORT ...]'")
        repo, user, eps = parts[0], parts[1], parts[2:]
        if not _REPO.match(repo):
            raise ValueError(f"line {n}: bad repo name {repo!r}")
        if not _USER.match(user):
            raise ValueError(f"line {n}: sandbox user must look like agent-xxx, got {user!r}")
        if repo in table:
            raise ValueError(f"line {n}: {repo} listed twice")
        if user in users:
            raise ValueError(f"line {n}: user {user} shared by two repos (each repo needs its own uid)")
        endpoints = []
        for ep in eps:
            m = re.match(r"^([0-9.]+):(\d+)$", ep)
            if not m:
                raise ValueError(f"line {n}: endpoint {ep!r} must be IPv4:port (IP literal, no names, no ranges)")
            ip = ipaddress.IPv4Address(m.group(1))          # raises ValueError on a bad address
            port = int(m.group(2))
            if not 1 <= port <= 65535:
                raise ValueError(f"line {n}: port {port} out of range")
            endpoints.append((str(ip), port))
        table[repo] = {"user": user, "endpoints": endpoints}
        users.add(user)
    return table


def ip_allow(table, repo):
    t = table[repo]
    ips = ["127.0.0.1", "::1", ROUTER[0]]
    for ip, _ in t["endpoints"]:
        if ip not in ips:
            ips.append(ip)
    return ips


def render_nft(table, uid_of):
    uids = {repo: uid_of(t["user"]) for repo, t in table.items()}
    all_uids = ", ".join(str(u) for u in uids.values())
    lines = [
        "# generated by agent_runner_egress.py from egress.conf -- do not edit",
        "table inet agent_egress",
        "delete table inet agent_egress",
        "table inet agent_egress {",
        "  chain output {",
        "    type filter hook output priority filter; policy accept;",
        f"    meta skuid {{ {all_uids} }} jump agent_out",
        "  }",
        "  chain agent_out {",
        '    oifname "lo" ip daddr 127.0.0.1 accept',
        '    oifname "lo" ip6 daddr ::1 accept',
        "    ct state established,related accept",
        f"    ip daddr {ROUTER[0]} tcp dport {ROUTER[1]} accept",
    ]
    for repo, t in table.items():
        for ip, port in t["endpoints"]:
            lines.append(f"    meta skuid {uids[repo]} ip daddr {ip} tcp dport {port} accept  # {repo}")
    lines += [
        "    reject with icmpx admin-prohibited",
        "  }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--conf", default=DEFAULT_CONF)
    ap.add_argument("cmd", choices=["user", "ip-allow", "render-nft", "users"])
    ap.add_argument("repo", nargs="?")
    a = ap.parse_args(argv)
    with open(a.conf) as f:
        table = parse(f.read())
    if a.cmd in ("user", "ip-allow"):
        if a.repo not in table:
            print(f"agent_runner_egress: repo {a.repo!r} has no sandbox entry in {a.conf}", file=sys.stderr)
            return 2
        print(table[a.repo]["user"] if a.cmd == "user" else " ".join(ip_allow(table, a.repo)))
    elif a.cmd == "users":
        print(" ".join(t["user"] for t in table.values()))
    else:
        import pwd                                        # Linux-only; the users must exist (setup-sandbox)
        sys.stdout.write(render_nft(table, lambda u: pwd.getpwnam(u).pw_uid))
    return 0


if __name__ == "__main__":
    sys.exit(main())
